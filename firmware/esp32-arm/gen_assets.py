# PlatformIO pre-build step (env:device): embeds the 0G system prompts and the arm calibration table into the
# firmware, byte for byte, so the robot's promptHash and armConfigHash equal the TypeScript program's.
import os

Import("env")  # noqa: F821  (PlatformIO SCons)

root = os.path.abspath(os.path.join(env["PROJECT_DIR"], "..", ".."))  # noqa: F821
out = os.path.join(env["PROJECT_DIR"], "src", "board", "assets.h")  # noqa: F821


def c_string(data: bytes) -> str:
    # raw bytes as a C string literal (UTF-8 kept exact; octal escapes for anything unsafe)
    parts = []
    for b in data:
        c = chr(b)
        if c == "\\":
            parts.append("\\\\")
        elif c == '"':
            parts.append('\\"')
        elif c == "\n":
            parts.append('\\n"\n  "')
        elif 32 <= b < 127:
            parts.append(c)
        else:
            parts.append("\\%03o" % b)
    return '"' + "".join(parts) + '"'


files = {
    "PROMPT_PLAN": "prompts/plan.txt",
    "PROMPT_VERIFY_GRASP": "prompts/verify_grasp.txt",
    "PROMPT_VERIFY_PLACE": "prompts/verify_place.txt",
    "PROMPT_INCIDENT": "prompts/incident.txt",
    "ARM_JSON": "config/arm.json",
}
lines = ["// GENERATED by gen_assets.py from prompts/*.txt and config/arm.json — do not edit.", "#pragma once", ""]
for name, rel in files.items():
    with open(os.path.join(root, rel), "rb") as f:
        lines.append(f"static const char {name}[] =\n  {c_string(f.read())};")
        lines.append("")
os.makedirs(os.path.dirname(out), exist_ok=True)
with open(out, "w") as f:
    f.write("\n".join(lines))
print("gen_assets: wrote", out)
